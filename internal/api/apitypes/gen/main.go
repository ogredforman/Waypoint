// Command gen writes the TypeScript types for the API (ADR 0001):
// types.gen.ts from the DTOs in internal/api/apitypes, via tygo, and
// enums.gen.ts from the enums in internal/domain. With -check it writes
// nothing and fails if the committed files are out of date. Run it from the
// repository root: make gen, or make lint for the check.
package main

import (
	"bytes"
	"flag"
	"fmt"
	"os"
	"path/filepath"
	"regexp"
	"strings"

	"github.com/gzuidhof/tygo/tygo"

	"github.com/ogredforman/waypoint/internal/domain"
)

const outDir = "web/src/lib/api"

// enum is one domain enum as it goes on the wire.
type enum struct {
	name   string
	values []string
}

func values[T ~string](vs []T) []string {
	out := make([]string, len(vs))
	for i, v := range vs {
		out[i] = string(v)
	}
	return out
}

// enums are the domain enums sent to the frontend. The values come from the
// domain's own lists, so they can't drift. tygo can't write these as unions:
// it only recognizes consts named after their type (TaskStatusTodo, not
// TaskTodo).
var enums = []enum{
	{"ProjectStatus", values(domain.ProjectStatuses())},
	{"TaskStatus", values(domain.TaskStatuses())},
	{"TaskSize", values(domain.TaskSizes())},
	{"Energy", values(domain.Energies())},
	{"ExtractionRunStatus", values(domain.ExtractionRunStatuses())},
	{"QuestionStatus", values(domain.QuestionStatuses())},
	{"ObservationKind", values(domain.ObservationKinds())},
	{"TargetType", values(domain.TargetTypes())},
	{"BlockerStatus", values(domain.BlockerStatuses())},
	{"IdeaStatus", values(domain.IdeaStatuses())},
	{"ChangesetSource", values(domain.ChangesetSources())},
	{"ChangesetStatus", values(domain.ChangesetStatuses())},
	{"OpType", values(domain.OpTypes())},
	{"ChangeOpStatus", values(domain.ChangeOpStatuses())},
	{"BriefingSource", values(domain.BriefingSources())},
	{"InterfaceFont", values(domain.InterfaceFonts())},
	{"DiaryFont", values(domain.DiaryFonts())},
}

func main() {
	check := flag.Bool("check", false, "fail if the generated files are out of date instead of writing them")
	flag.Parse()
	if err := run(*check); err != nil {
		fmt.Fprintln(os.Stderr, "gen:", err)
		os.Exit(1)
	}
}

func run(check bool) error {
	tmp, err := os.MkdirTemp("", "waypoint-gen-")
	if err != nil {
		return err
	}
	defer func() { _ = os.RemoveAll(tmp) }()

	files := map[string][]byte{"enums.gen.ts": enumsTS()}
	types, err := typesTS(tmp)
	if err != nil {
		return err
	}
	files["types.gen.ts"] = types

	var stale []string
	for name, want := range files {
		path := filepath.Join(outDir, name)
		if check {
			got, err := os.ReadFile(path)
			if err != nil || !bytes.Equal(got, want) {
				stale = append(stale, path)
			}
			continue
		}
		if err := os.WriteFile(path, want, 0o644); err != nil {
			return err
		}
	}
	if len(stale) > 0 {
		return fmt.Errorf("out of date, run make gen: %s", strings.Join(stale, ", "))
	}
	return nil
}

func enumsTS() []byte {
	var b bytes.Buffer
	b.WriteString("// Code generated by internal/api/apitypes/gen from internal/domain. DO NOT EDIT.\n")
	for _, e := range enums {
		quoted := make([]string, len(e.values))
		for i, v := range e.values {
			quoted[i] = fmt.Sprintf("%q", v)
		}
		list := strings.ToLower(e.name[:1]) + e.name[1:] + "Values"
		fmt.Fprintf(&b, "\nexport const %s = [%s] as const;\n", list, strings.Join(quoted, ", "))
		fmt.Fprintf(&b, "export type %s = (typeof %s)[number];\n", e.name, list)
	}
	return b.Bytes()
}

// untyped matches what tygo writes for a Go type it has no mapping for:
// any /* pkg.Type */.
var untyped = regexp.MustCompile(`\bany /\*`)

// typesTS runs tygo over apitypes into dir and returns the output.
func typesTS(dir string) ([]byte, error) {
	mappings := map[string]string{"time.Time": "string"}
	for _, e := range enums {
		mappings["domain."+e.name] = "domain." + e.name
	}
	out := filepath.Join(dir, "types.gen.ts")
	g := tygo.New(&tygo.Config{Packages: []*tygo.PackageConfig{{
		Path:         "github.com/ogredforman/waypoint/internal/api/apitypes",
		OutputPath:   out,
		Indent:       "  ",
		TypeMappings: mappings,
		Frontmatter:  `import type * as domain from "./enums.gen";` + "\n",
		EnumStyle:    "union",
	}}})
	if err := g.Generate(); err != nil {
		return nil, err
	}
	// Generate ignores write errors, so a missing file means it failed.
	b, err := os.ReadFile(out)
	if err != nil {
		return nil, fmt.Errorf("tygo wrote nothing: %w", err)
	}
	if loc := untyped.FindIndex(b); loc != nil {
		line := bytes.Count(b[:loc[0]], []byte("\n")) + 1
		return nil, fmt.Errorf("types.gen.ts line %d has an any type: map the Go type in gen or give the field a tstype tag", line)
	}
	return b, nil
}
